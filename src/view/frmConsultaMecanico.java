    private void btnLocalizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLocalizarActionPerformed
        String pesquisa = txtPesquisa.getText().trim();
        
        if(pesquisa.isEmpty()){
            JOptionPane.showMessageDialog(this, "Digite a pasquisa ou parte dela", "Pesquisa vazia", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        DefaultTableModel modelo = (DefaultTableModel) tblMecanico.getModel();
        
        modelo.setRowCount(0);
        
        String tipo_pesquisa = cmbPesquisarPor.getSelectedItem().toString();
        
        String sql = "";
        
        if(tipo_pesquisa == "ID"){
            sql = "SELECT * FROM mecanico WHERE id = ? ORDER BY id";
        }
        if(tipo_pesquisa == "Nome"){
            sql = "SELECT * FROM mecanico WHERE nome ILIKE ? ORDER BY id";
        }
        if(tipo_pesquisa == "Especialidade"){
            sql = "SELECT * FROM mecanico WHERE especialidade ILIKE ? ORDER BY id";
        }
        
        try (Connection conex = Conexao.conectar();
             PreparedStatement stmt = conex.prepareStatement(sql)){
            
            
            if(tipo_pesquisa == "ID"){
                stmt.setInt(1, Integer.parseInt(pesquisa));
            }else{
                stmt.setString(1, "%" + pesquisa + "%");
            }
            
            try (ResultSet resultado = stmt.executeQuery()){
                while (resultado.next()){
                    modelo.addRow(new Object [] {
                        resultado.getInt("id"),
                        resultado.getString("nome"),
                        resultado.getString("especialidade"),
                        resultado.getString("telefone"),
                        resultado.getString("data_admissao"),
                        resultado.getString("observacao"),
                        resultado.getBoolean("ativo")
                    });
                }
            }
            
            if(modelo.getRowCount() == 0){
                JOptionPane.showMessageDialog(this, "Nenhum mecanico encontrado para: " + pesquisa, "Resultado da Pesquisa", JOptionPane.INFORMATION_MESSAGE);
            }
        } catch (SQLException erro){
            JOptionPane.showMessageDialog(this,
                "Erro ao localizar mecanico:\n" + erro.getMessage(),
                "Erro no banco de dados",
                JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnLocalizarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        int linha = tblMecanico.getSelectedRow();
        
        if(linha == -1){
           JOptionPane.showMessageDialog(this,"Selecione um mecanico para excluir!");
           return; 
        }
        
        int id = Integer.parseInt(tblMecanico.getValueAt(linha, 0).toString());
        
        int resposta = JOptionPane.showConfirmDialog(this, 
            "Deseja realmente excluir o mecanico do ID "+ id + " ?",
            "Confirmar Exclusão",
            JOptionPane.YES_NO_CANCEL_OPTION,
            JOptionPane.QUESTION_MESSAGE);
        
        if (resposta != JOptionPane.YES_OPTION) {
            return;
        }
        
        String sql = "DELETE FROM mecanico WHERE id = ?";
        
        try (Connection conex = Conexao.conectar();
                PreparedStatement stmt = conex.prepareStatement(sql)){
            
            stmt.setInt(1, id);
            
            int registros = stmt.executeUpdate();
            if (registros > 0){
                JOptionPane.showMessageDialog(this, "Mecanico excluido com sucesso!");
                atualizarTabela();
            } else {
                JOptionPane.showMessageDialog(this, "Mecanico não encontrado!");
            }
        } catch (SQLException erro){
            JOptionPane.showMessageDialog(this, "Erro ao excluir mecanico: " + erro.getMessage());
        }
    }//GEN-LAST:event_btnExcluirActionPerformed

