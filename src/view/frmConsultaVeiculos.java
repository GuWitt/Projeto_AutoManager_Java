    private void btnLocalizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLocalizarActionPerformed
        String pesquisa = txtPesquisa.getText().trim();
        
        if(pesquisa.isEmpty()){
            JOptionPane.showMessageDialog(this, "Digite a pasquisa ou parte dela", "Pesquisa vazia", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        DefaultTableModel modelo = (DefaultTableModel) tblVeiculos.getModel();
        
        modelo.setRowCount(0);
        
        String tipo_pesquisa = cmbPesquisarPor.getSelectedItem().toString();
        
        String sql = "";
        
        if(tipo_pesquisa == "ID"){
            sql = "SELECT * FROM veiculo WHERE id = ? ORDER BY id";
        }
        if(tipo_pesquisa == "Placa"){
            sql = "SELECT * FROM veiculo WHERE placa ILIKE ? ORDER BY placa";
        }
        if(tipo_pesquisa == "Marca"){
            sql = "SELECT * FROM veiculo WHERE marca ILIKE ? ORDER BY marca";
        }
        if(tipo_pesquisa == "Modelo"){
            sql = "SELECT * FROM veiculo WHERE modelo ILIKE ? ORDER BY modelo";
        }
        if(tipo_pesquisa == "Cliente"){
            sql = "SELECT * FROM veiculo WHERE cliente_id = ? ORDER BY cliente_id";
        }
        
        try (Connection conex = Conexao.conectar();
             PreparedStatement stmt = conex.prepareStatement(sql)){
            
            
            if(tipo_pesquisa.equals("ID")){
                stmt.setInt(1, Integer.parseInt(pesquisa));
            }else{
                stmt.setString(1, "%" + pesquisa + "%");
            }
            
            try (ResultSet resultado = stmt.executeQuery()){
                while (resultado.next()){
                    modelo.addRow(new Object [] {
                        resultado.getInt("id"),
                        resultado.getInt("cliente_id"),
                        resultado.getString("placa"),
                        resultado.getString("marca"),
                        resultado.getString("modelo"),
                        resultado.getInt("ano"),
                        resultado.getString("cor"),
                        resultado.getString("observacao"),
                        resultado.getBoolean("ativo") ? "Sim" : "Não"
                    });
                }
            }
            
            if(modelo.getRowCount() == 0){
                JOptionPane.showMessageDialog(this, "Nenhum veiculo encontrado para: " + pesquisa, "Resultado da Pesquisa", JOptionPane.INFORMATION_MESSAGE);
            }
        } catch (SQLException erro){
            JOptionPane.showMessageDialog(this,
                "Erro ao localizar veiculo:\n" + erro.getMessage(),
                "Erro no banco de dados",
                JOptionPane.ERROR_MESSAGE);
        } 
    }//GEN-LAST:event_btnLocalizarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        int linha = tblVeiculos.getSelectedRow();
        
        if(linha == -1){
           JOptionPane.showMessageDialog(this,"Selecione um cliente para excluir!");
           return; 
        }
        
        int id = Integer.parseInt(tblVeiculos.getValueAt(linha, 0).toString());
        
        int resposta = JOptionPane.showConfirmDialog(this, 
            "Deseja realmente excluir o veiculo do ID "+ id + " ?",
            "Confirmar Exclusão",
            JOptionPane.YES_NO_CANCEL_OPTION,
            JOptionPane.QUESTION_MESSAGE);
        
        if (resposta != JOptionPane.YES_OPTION) {
            return;
        }
        
        String sql = "DELETE FROM veiculo WHERE id = ?";
        
        try (Connection conex = Conexao.conectar();
                PreparedStatement stmt = conex.prepareStatement(sql)){
            
            stmt.setInt(1, id);
            
            int registros = stmt.executeUpdate();
            if (registros > 0){
                JOptionPane.showMessageDialog(this, "Veiculo excluido com sucesso!");
                atualizarTabela();
            } else {
                JOptionPane.showMessageDialog(this, "Veiculo não encontrado!");
            }
        } catch (SQLException erro){
            JOptionPane.showMessageDialog(this, "Erro ao excluir veiculo: " + erro.getMessage());
        }
    }//GEN-LAST:event_btnExcluirActionPerformed

    private void btnAlterarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAlterarActionPerformed
        int linha = tblVeiculos.getSelectedRow();
         
         if (linha == -1){
             JOptionPane.showMessageDialog(this,"Selecione um veiculo na tabela para alterar");
             return;
         }
         
         //2. Pegar o ID da limha selecionada
         // O ID não será alterado.
         int id = Integer.parseInt(tblVeiculos.getValueAt(linha,0).toString());
         
         //3. Ler os novos valores digitados nos campos especie,nome, idade
         int cliente = Integer.parseInt(txtCliente.getText());
         String placa = txtPlaca.getText().trim();
         String marca = txtMarca.getText().trim();
         String modelo = txtModelo.getText().trim();
         String ano = txtAno.getText();
         String cor = cmbCor.getSelectedItem().toString();
         String observacao = txtObservacao.getText();
         boolean ativo = chkAtivo.isSelected();
         
         //4. Validar se todos os campos estão preenchidos
         if (placa.isEmpty() || marca.isEmpty() || modelo.isEmpty() || ano.isEmpty()) {
             JOptionPane.showMessageDialog(this, "Preecha os campos OBRIGATÓRIOS");
             return;
         }
         
        
         // 6. Pedir Confirmação antes de gravar no banco de dados
         int resposta = JOptionPane.showConfirmDialog(this, 
                         "Deseja alterar os dados do cliente de ID "+id+"?" ,
                         "Confirmar Alteração",
                         JOptionPane.YES_NO_CANCEL_OPTION,
                         JOptionPane.QUESTION_MESSAGE);
         if (resposta != JOptionPane.YES_OPTION) {
             return;
         }
         
         // 7. Alteramos apenas a escpecie, nome e idade
         // O WHERE garante que somente o animal selecionado será atualziado
         
         String sql = """
                      UPDATE veiculo
                      SET cliente_id = ?, placa = ?, marca = ?, modelo = ?, ano = ?, cor = ?, observacao = ?, ativo = ?
                      WHERE id = ?
                      """;
         
         try (Connection conex = Conexao.conectar();
              PreparedStatement stmt = conex.prepareStatement(sql)){
             //8. Preecher os Parametros(?) na mesma ordem do SQL
             stmt.setInt(1, cliente);
             stmt.setString(2, placa);
             stmt.setString(3, marca);
             stmt.setString(4, modelo);
             stmt.setInt(5, Integer.parseInt(ano));
             stmt.setString(6, cor);
             stmt.setString(7, observacao);
             stmt.setBoolean(8, ativo);
             stmt.setInt(9, id);
             
             //9. Executamos a alteração no Banco de Dados
             int registros = stmt.executeUpdate();
             if (registros > 0){
                 JOptionPane.showMessageDialog(this, "Veiculo alterado com sucesso!");
                 atualizarTabela();
                 txtID.setText("");
                 txtPlaca.setText("");
                 txtMarca.setText("");
                 txtModelo.setText("");
                 txtAno.setText("");
                 chkAtivo.setSelected(false);
                 txtPesquisa.requestFocus();
             } else {
                 JOptionPane.showMessageDialog(this, "Veiculo não encontrado");
             }
         } catch (SQLException erro){
           JOptionPane.showConfirmDialog(this, "Erro ao alterar veiculo: " + erro.getMessage());
         }
    }//GEN-LAST:event_btnAlterarActionPerformed

