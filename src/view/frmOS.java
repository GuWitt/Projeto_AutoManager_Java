    private void btnCadastrarOSActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCadastrarOSActionPerformed
         String sqlInsert = """
                           INSERT INTO ordem_servico
                           (veiculo_id, mecanico_id, servico_id, descricao_problema, diagnostico, status, valor_cobrado, observacao)
                           VALUES (?, ?, ?, ?, ?, ?, ?, ?)
                           """;
        
        try{
            Connection conex = Conexao.conectar();
            PreparedStatement stmt = conex.prepareStatement(sqlInsert);
            
            int veiculo_id = Integer.parseInt(txtIDVeiculo.getText());
            int mecanico_id = Integer.parseInt(txtIDMecanico.getText());
            int servico_id = Integer.parseInt (txtIDServico.getText());
            String descricao_problema = txtDescricao.getText();
            String diagnostico = txtDiagnostico.getText();
            String status = cmbStatus.getSelectedItem().toString();
            Float valor_cobrado = Float.parseFloat(txtValorCobrado.getText());
            String observacao = txtObservacao.getText();
             
             
            if(veiculo_id <0 || mecanico_id <0 || servico_id <0 || descricao_problema == "" || diagnostico == "" || status == "" || valor_cobrado <0 || observacao == ""){
                JOptionPane.showMessageDialog(this, "Preencha corretamente os campos, nenhum deve ser vazio!");
                return;
            }
            
            stmt.setInt(1, veiculo_id);
            stmt.setInt(2, mecanico_id);
            stmt.setInt(3, servico_id);
            stmt.setString(4, descricao_problema);
            stmt.setString(5, diagnostico);
            stmt.setString(6, status);
            stmt.setFloat(7, valor_cobrado);
            stmt.setString(8, observacao);
            
            
            int linhas = stmt.executeUpdate();
            if (linhas > 0){
                JOptionPane.showMessageDialog(this, "Cadastro realizado com sucesso!");
                limparCampos();
            }
        } catch (SQLException erro){
           JOptionPane.showMessageDialog(this,"Não foi possível Cadastrar! - Erro: "+ erro); 
        }
    }//GEN-LAST:event_btnCadastrarOSActionPerformed

    private void btnBuscarVeiculoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarVeiculoActionPerformed
        String sqlSelect = """
        SELECT id, placa, marca, modelo
        FROM veiculo
        WHERE id = ? AND ativo = TRUE
        """;

        try (Connection conex = Conexao.conectar();
        PreparedStatement stmt = conex.prepareStatement(sqlSelect)) {

        int id  = Integer.parseInt(txtIDVeiculo.getText().trim().toString());

   
        stmt.setInt(1, id);

        try (ResultSet rs = stmt.executeQuery()) {

            if (rs.next()) {

             txtVeiculo.setText(
                    rs.getString("placa") + " - " +
                    rs.getString("marca") + " " +
                    rs.getString("modelo")
            );

        } else {
            JOptionPane.showMessageDialog(this,
                "Veículo não encontrado ou inativo!");
        }
    }

} catch (SQLException erro) {

    JOptionPane.showMessageDialog(this,
        "Não foi possível localizar o veículo!\nErro: " +
        erro.getMessage());
}
    }//GEN-LAST:event_btnBuscarVeiculoActionPerformed

