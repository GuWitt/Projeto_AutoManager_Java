    private void btnAlterarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAlterarActionPerformed
        int linha = tblOS.getSelectedRow();
         
         if (linha == -1){
             JOptionPane.showMessageDialog(this,"Selecione uma Ordem de Serviço na tabela para alterar");
             return;
         }
         
         //2. Pegar o ID da limha selecionada
         // O ID não será alterado.
         int id = Integer.parseInt(tblOS.getValueAt(linha,0).toString());
         
         //3. Ler os novos valores digitados nos campos especie,nome, idade
         int IDMecanico = Integer.parseInt(txtIDMecanico.getText().trim());
         int IDServico = Integer.parseInt(txtIDServico.getText().toString());
         String status = cmbStatus.getSelectedItem().toString();
         float valorCobrado = Float.parseFloat(txtValorCobrado.getText().trim());
         int IDVeiculo = Integer.parseInt(txtIDVeiculo.getText().trim());
         
         //4. Validar se todos os campos estão preenchidos
         
         
        
         // 6. Pedir Confirmação antes de gravar no banco de dados
         int resposta = JOptionPane.showConfirmDialog(this, 
                         "Deseja alterar os dados da Ordem de Serviço de ID "+id+"?" ,
                         "Confirmar Alteração",
                         JOptionPane.YES_NO_CANCEL_OPTION,
                         JOptionPane.QUESTION_MESSAGE);
         if (resposta != JOptionPane.YES_OPTION) {
             return;
         }
         
         // 7. Alteramos apenas a escpecie, nome e idade
         // O WHERE garante que somente o animal selecionado será atualziado
         
         String sql = """
                      UPDATE ordem_servico
                      SET mecanico_id = ?, servico_id = ?, status = ?, valor_cobrado = ?, veiculo_id = ? 
                      WHERE id = ?
                      """;
         
         try (Connection conex = Conexao.conectar();
              PreparedStatement stmt = conex.prepareStatement(sql)){
             //8. Preecher os Parametros(?) na mesma ordem do SQL
             stmt.setInt(1, IDMecanico);
             stmt.setInt(2, IDServico);
             stmt.setString(3, status);
             stmt.setFloat(4, valorCobrado);
             stmt.setInt(5, IDVeiculo);
             stmt.setInt(6, id);
             
             //9. Executamos a alteração no Banco de Dados
             int registros = stmt.executeUpdate();
             if (registros > 0){
                 JOptionPane.showMessageDialog(this, "Ordem de Serviço alterado com sucesso!");
                 atualizarTabela();
                 limparCampos();
             } else {
                 JOptionPane.showMessageDialog(this, "Ordem de Serviço não encontrado");
             }
         } catch (SQLException erro){
           JOptionPane.showConfirmDialog(this, "Erro ao alterar Ordem de Serviço: " + erro.getMessage());
         }
    }//GEN-LAST:event_btnAlterarActionPerformed

